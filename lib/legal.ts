/** BRIXA's company as set in its panel. */
export type ProviderDetails = {
  company_name: string | null;
  eik: string | null;
  vat_number?: string | null;
  address: string | null;
  representative?: string | null;
  email: string | null;
  phone?: string | null;
  website?: string | null;
};

/** "Брикса ЕООД, ЕИК 123456789, София, ул. …, office@…" — whatever BRIXA has filled in. */
export function providerLine(details: ProviderDetails | null) {
  if (!details?.company_name) return "доставчика на BRIXA";
  return [details.company_name, details.eik && `ЕИК ${details.eik}`, details.address, details.email].filter(Boolean).join(", ");
}

/** BRIXA's details as the Electronic Commerce Act asks (чл. 4 ЗЕТ): each line "label: value" ("—" while not filled in). */
export function providerRows(details: ProviderDetails | null): [string, string][] {
  const d = details ?? ({} as Partial<ProviderDetails>);
  return [
    ["Наименование", d.company_name || "—"],
    ["ЕИК", d.eik || "—"],
    ...(d.vat_number ? ([["Идентификационен номер по ДДС", d.vat_number]] as [string, string][]) : []),
    ["Седалище и адрес на управление", d.address || "—"],
    ...(d.representative ? ([["Представлявано от", d.representative]] as [string, string][]) : []),
    ["Имейл", d.email || "—"],
    ...(d.phone ? ([["Телефон", d.phone]] as [string, string][]) : []),
    ...(d.website ? ([["Уебсайт", d.website]] as [string, string][]) : []),
    ["Регистър", "Търговски регистър и регистър на ЮЛНЦ към Агенцията по вписванията"],
  ];
}

/** "13 октомври 2026 г." */
export function legalDate(iso: string) {
  const [y, m, d] = iso.split("-").map(Number);
  const months = ["януари", "февруари", "март", "април", "май", "юни", "юли", "август", "септември", "октомври", "ноември", "декември"];
  return `${d} ${months[m - 1]} ${y} г.`;
}

/** A text with its placeholders filled in. */
export function fillLegal(text: string, vars: { provider: string; trialDays: number }) {
  const date = legalDate(LEGAL_VERSION);
  return (
    text
      .split("{provider}")
      .join(vars.provider)
      .split("{trialDays}")
      .join(String(vars.trialDays))
      // the date ends with "г." — no second full stop after it
      .split("{version}.")
      .join(date)
      .split("{version}")
      .join(date)
  );
}

