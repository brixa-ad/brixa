export const dictionaries: Record<Lang, Dictionary> = { bg, en };

export function isLang(value: unknown): value is Lang {
  return value === "bg" || value === "en";
}

/** Replace {placeholders} in a dictionary string. */
export function fmt(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? ""));
}

/** Pick the English name of a lookup row when available. */
export function localName(row: { name: string; name_en?: string | null }, lang: Lang) {
  return lang === "en" && row.name_en ? row.name_en : row.name;
}

export function locale(lang: Lang) {
  return lang === "en" ? "en-GB" : "bg-BG";
}
